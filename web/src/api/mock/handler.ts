function collectMockOutlineCardIds(nodes: OutlineNode[]): Set<string> {
  const ids = new Set<string>()
  for (const node of nodes) {
    if (node.type === 'card_ref') ids.add(node.card_id)
    else {
      for (const childId of collectMockOutlineCardIds(node.children)) ids.add(childId)
    }
  }
  return ids
}

function validateMockProposal(proposal: Proposal): ValidationErrorItem[] {
  const errors: ValidationErrorItem[] = []
  proposal.payload.operations.forEach((op, index) => {
    if (op.op === 'knowledge_card') {
      if (!op.data.title.trim()) {
        errors.push({
          op_index: index,
          temp_ref: op.temp_ref ?? null,
          field_path: 'title',
          rule: 'operation_shape',
          message: 'title cannot be empty',
        })
      }
    }
    if (op.op === 'question_card') {
      if (
        (op.data.answer_source_kind === 'inferred' ||
          op.data.answer_source_kind === 'original_authored') &&
        !(op.data.answer_basis ?? '').trim()
      ) {
        errors.push({
          op_index: index,
          temp_ref: op.temp_ref ?? null,
          field_path: 'answer_basis',
          rule: 'answer_provenance',
          message: 'answer_basis is required when answer_source_kind is inferred or original_authored',
        })
      }
      if (op.data.answer_source_kind === 'inferred' && op.data.anchor_ids.length === 0) {
        errors.push({
          op_index: index,
          temp_ref: op.temp_ref ?? null,
          field_path: 'anchor_ids',
          rule: 'answer_provenance',
          message: 'inferred answers require at least one source anchor',
        })
      }
    }
  })
  return errors
}

function buildMinimalPdf(title: string, subtitle: string): Blob {
  const safe = (s: string) => s.replace(/[^\x20-\x7e]/g, '?').replace(/[()\\]/g, '\\$&')
  const stream = `BT /F1 18 Tf 56 740 Td (${safe(title)}) Tj 0 -28 Td /F1 12 Tf (${safe(subtitle)}) Tj 0 -24 Td (Generated by Reinforce mock export preview.) Tj ET`
  const objects = [
    '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj',
    '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj',
    '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj',
    `4 0 obj << /Length ${stream.length} >> stream\n${stream}\nendstream endobj`,
    '5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj',
  ]
  let pdf = '%PDF-1.4\n'
  const offsets: number[] = [0]
  for (const obj of objects) {
    offsets.push(pdf.length)
    pdf += `${obj}\n`
  }
  const xrefPos = pdf.length
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
  for (let i = 1; i < offsets.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`
  }
  pdf += `trailer << /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF\n`
  return new Blob([pdf], { type: 'application/pdf' })
}

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff
  for (const byte of bytes) {
    crc ^= byte
    for (let j = 0; j < 8; j += 1) {
      crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1))
    }
  }
  return (crc ^ 0xffffffff) >>> 0
}

function buildMinimalZip(filename: string, content: string): Blob {
  const enc = new TextEncoder()
  const nameBytes = enc.encode(filename)
  const dataBytes = enc.encode(content)
  const crc = crc32(dataBytes)

  const localHeader = new ArrayBuffer(30 + nameBytes.length)
  const lv = new DataView(localHeader)
  lv.setUint32(0, 0x04034b50, true)
  lv.setUint16(4, 20, true)
  lv.setUint16(6, 0, true)
  lv.setUint16(8, 0, true)
  lv.setUint16(10, 0, true)
  lv.setUint16(12, 0, true)
  lv.setUint32(14, crc, true)
  lv.setUint32(18, dataBytes.length, true)
  lv.setUint32(22, dataBytes.length, true)
  lv.setUint16(26, nameBytes.length, true)
  lv.setUint16(28, 0, true)
  new Uint8Array(localHeader, 30).set(nameBytes)

  const cdOffset = localHeader.byteLength + dataBytes.length
  const cdHeader = new ArrayBuffer(46 + nameBytes.length)
  const cv = new DataView(cdHeader)
  cv.setUint32(0, 0x02014b50, true)
  cv.setUint16(4, 20, true)
  cv.setUint16(6, 20, true)
  cv.setUint16(8, 0, true)
  cv.setUint16(10, 0, true)
  cv.setUint16(12, 0, true)
  cv.setUint16(14, 0, true)
  cv.setUint32(16, crc, true)
  cv.setUint32(20, dataBytes.length, true)
  cv.setUint32(24, dataBytes.length, true)
  cv.setUint16(28, nameBytes.length, true)
  cv.setUint16(30, 0, true)
  cv.setUint16(32, 0, true)
  cv.setUint16(34, 0, true)
  cv.setUint16(36, 0, true)
  cv.setUint32(38, 0, true)
  cv.setUint32(42, 0, true)
  new Uint8Array(cdHeader, 46).set(nameBytes)

  const eocd = new ArrayBuffer(22)
  const ev = new DataView(eocd)
  ev.setUint32(0, 0x06054b50, true)
  ev.setUint16(4, 0, true)
  ev.setUint16(6, 0, true)
  ev.setUint16(8, 1, true)
  ev.setUint16(10, 1, true)
  ev.setUint32(12, cdHeader.byteLength, true)
  ev.setUint32(16, cdOffset, true)
  ev.setUint16(20, 0, true)

  return new Blob([localHeader, dataBytes, cdHeader, eocd], { type: 'application/zip' })
}

